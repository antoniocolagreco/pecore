import { z } from "zod";

export const NodeOutputType = z.enum(["spec", "code_review", "code_analysis", "sha", "pull_request", "feedback", "log"]);
export const ArtifactType = NodeOutputType.or(z.literal("diff"));
export type ArtifactType = z.infer<typeof ArtifactType>;

export const Artifact = z.object({
  type: ArtifactType.or(z.literal("attachment")),
  jobId: z.string().min(1),
  run: z.string().min(1),
  name: z.string().min(1),
  sha256: z.string().regex(/^[0-9a-f]{64}$/),
  filesHash: z.string().nullable(),
});
export type Artifact = z.infer<typeof Artifact>;

const description = z.string().trim().min(1);
const hunk = z.number().int().nonnegative();
export const SpecArtifact = z.strictObject({
  feature: description,
  scenarios: z.array(z.strictObject({
    name: description,
    given: z.array(description).min(1),
    when: description,
    then: z.array(description).min(1),
    examples: z.array(z.record(z.string(), z.string())).min(1).optional(),
  })).min(1),
});
export type SpecArtifact = z.infer<typeof SpecArtifact>;

export const CodeReviewComment = z.strictObject({
  file: description,
  line: z.number().int().positive().optional(),
  hunk: hunk.optional(),
  text: description,
}).refine(({ line, hunk }) => line !== undefined || hunk !== undefined, "Choose a line or hunk.");
export const CodeReviewArtifact = z.strictObject({
  body: z.string(),
  comments: z.array(CodeReviewComment),
});
export type CodeReviewArtifact = z.infer<typeof CodeReviewArtifact>;

export const CodeAnalysisArtifact = z.strictObject({
  summary: description,
  hunks: z.array(z.strictObject({
    file: description,
    hunk,
    level: z.enum(["risky", "safe"]),
    text: description,
  })),
});
export type CodeAnalysisArtifact = z.infer<typeof CodeAnalysisArtifact>;

export const ShaArtifact = z.string().regex(/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/);
export const PullRequestArtifact = z.strictObject({
  title: description,
  body: z.string(),
  url: z.url().optional(),
});
export type PullRequestArtifact = z.infer<typeof PullRequestArtifact>;

export const artifactTypes: Readonly<Record<ArtifactType, { readonly description: string; readonly schema: z.ZodType; readonly plain?: true }>> = {
  spec: { description: "one feature and its BDD scenarios with given, when and then", schema: SpecArtifact },
  diff: { description: "a patch generated by Git", schema: z.string(), plain: true },
  code_review: { description: "a general review and comments on specific lines or hunks", schema: CodeReviewArtifact },
  code_analysis: { description: "a summary and a safe or risky classification for every hunk", schema: CodeAnalysisArtifact },
  sha: { description: "the SHA of the commit", schema: ShaArtifact, plain: true },
  pull_request: { description: "a pull request title and body, with its URL after delivery", schema: PullRequestArtifact },
  feedback: { description: "feedback for whoever needs to revise the work", schema: description, plain: true },
  log: { description: "execution output", schema: z.string(), plain: true },
};

export function artifactContentProblem(type: ArtifactType, content: string): string | null {
  const entry = artifactTypes[type];
  let value: unknown = content;
  if (!entry.plain) {
    try {
      value = JSON.parse(content);
    } catch (error) {
      return `Invalid JSON: ${(error as Error).message}`;
    }
  }
  const checked = entry.schema.safeParse(value);
  return checked.success ? null : checked.error.issues.map((issue) => `${issue.path.join(".") || "/"} ${issue.message}`).join("; ");
}
